#!/bin/bash

# Функция вывода справки
show_help() {
    echo "Использование: $0 --dir=\"путь1\" [--dir=\"путь2\" ...]"
    echo "               $0 -h | --help"
    echo
    echo "Описание:"
    echo "  Скрипт рекурсивно обходит указанные директории и собирает содержимое"
    echo "  всех текстовых файлов в один общий файл с именем директории и расширением .js."
    echo "  В начале содержимого каждого файла добавляется комментарий с его исходным путем."
    echo "  Бинарные файлы (картинки, gif, шрифты) автоматически игнорируются."
    echo
    echo "Параметры:"
    echo "  --dir=PATH    Путь к директории для обработки. Можно указывать несколько раз."
    echo "  -h, --help    Показать эту справку и выйти."
    exit 0
}

# Если скрипт запущен без параметров, сразу выводим справку
if [ $# -eq 0 ]; then
    show_help
fi

# Массив для хранения путей директорий
DIRS=()

# Разбор параметров командной строки
while [[ $# -gt 0 ]]; do
    case "$1" in
        -h|--help)
            show_help
            ;;
        --dir=*)
            # Извлекаем путь после знака "="
            DIRS+=("${1#*=}")
            shift
            ;;
        *)
            echo "Ошибка: Неизвестный параметр '$1'" >&2
            echo "Используйте $0 --help для вывода справки." >&2
            exit 1
            ;;
    esac
done

# Проверка на случай, если параметры были, но --dir среди них не оказалось
if [ ${#DIRS[@]} -eq 0 ]; then
    echo "Ошибка: Не указана ни одна директория через параметр --dir." >&2
    echo "Используйте $0 --help для вывода справки." >&2
    exit 1
fi

# Основной цикл обработки директорий
for dir in "${DIRS[@]}"; do
    # Удаляем слеш в конце пути, если он есть, для корректного имени файла
    clean_dir="${dir%/}"

    # Проверяем существование директории
    if [ ! -d "$clean_dir" ]; then
        echo "Предупреждение: Директория '$clean_dir' не существует. Пропускаем." >&2
        continue
    fi

    # Имя результирующего файла (например, dirname1.js)
    output_file="merges/$(basename "$clean_dir").txt"
    
    # Очищаем или создаем пустой файл перед записью
    > "$output_file"

    echo "Обработка директории '$clean_dir' -> Выходной файл: '$output_file'..."

    # Рекурсивный поиск всех файлов в директории
    find "$clean_dir" -type f | sort | while read -r filepath; do
        
        # Проверяем кодировку файла. Если это binary — пропускаем его.
        if file --mime-encoding "$filepath" | grep -q "binary"; then
            echo "  [Пропущен бинарный файл]: $filepath"
            continue
        fi
        
        # Записываем комментарий с путем к файлу
        echo "// $filepath" >> "$output_file"
        
        # Добавляем содержимое файла
        cat "$filepath" >> "$output_file"
        
        # Добавляем пустую строку для разделения файлов
        echo "" >> "$output_file"
    done
done

echo "Готово!"
